/**
 * Every sentence about received messages (M4-DESIGN §3.11, §5.1, §9.1): the kind badges, the "automatic reply" reason
 * words, the "why" lines of a possible reply, the reply notifications and the activity summaries. The processor, the
 * reply actions, Simulate and the tests all build their text here, so they agree. Pure and browser-safe.
 */

/** Badge words per stored kind (A6 wording). */
export const INBOUND_KIND_LABELS: Readonly<Record<InboundKindValue, string>> = {
  REPLY: "Reply",
  AUTO_REPLY: "Automatic reply",
  BOUNCE_NOTICE: "Delivery failure notice",
  POSSIBLE_REPLY: "Real reply?",
  UNLINKED: "Reply we couldn't link to a company",
  TEST_REPLY: "Reply to a test email",
};

const AUTO_REASON_LABELS: Readonly<Record<string, string>> = {
  "out-of-office": "out of office",
  "auto-reply": "automatic reply",
  "helpdesk-ack": "help desk confirmation",
  challenge: "spam filter check",
  "left-company": "has left the company",
  "read-receipt": "read receipt",
  dsn: "delivery failure",
  delay: "delivery delay",
  "process-failed": "couldn't be read",
  internal: "sent by your team",
  spam: "marked as spam by Mailgun",
};

/**
 * `InboundMessage.autoReason` in a few words ("out of office", "delivery failure", "marked as spam by Mailgun"), for
 * activity summaries and the Owner's "Messages we couldn't link". Unknown or missing → "automatic reply".
 */
export function autoReasonLabel(reason: string | null | undefined): string {
  return (reason && AUTO_REASON_LABELS[reason]) || "automatic reply";
}

// ───────────────────────── "why" lines (§9.1.1) ─────────────────────────

const WHY_LOG_ONLY = "It was recovered from Mailgun's log without its text, because the PC was off too long.";
const WHY_PROCESS_FAILED = "The app couldn't read this message, so it held the company's follow-ups to be safe. Open it in your inbox.";
const WHY_FALLBACK = "Some signs say it was sent automatically.";

/** Signal → line, in the order the lines are shown. */
const WHY_LINES: ReadonlyArray<{ line: string; match: (signal: string) => boolean }> = [
  { line: "It looks like a spam filter asking you to confirm you're a person.", match: (s) => s === "challenge" },
  { line: "It looks like an automatic \"we received your message\" confirmation.", match: (s) => s === "ack" || s === "body:ack" },
  { line: "It came through a help desk, which marks every email as automatic.", match: (s) => s === "helpdesk" || s === "helpdesk-mailer" },
  { line: "It says when they're back, like an out-of-office message.", match: (s) => s === "body:absence-details" },
  { line: "It says they're away, but it may also contain a real answer.", match: (s) => s === "body:absence" },
  {
    line: "It carries a \"don't auto-reply\" marker that some mail programs add to normal emails too.",
    match: (s) => s === "x-auto-response-suppress",
  },
  { line: "It mentions someone leaving the company.", match: (s) => s === "body:left-company" },
  { line: "Its subject mentions a holiday or leave.", match: (s) => s === "subject:absence-word" },
  {
    line: "It looks like a newsletter or mailing-list email.",
    match: (s) => s === "list-headers" || s === "feedback-id" || (s.startsWith("precedence:") && s !== "precedence:auto_reply"),
  },
  { line: "It came from a no-reply address.", match: (s) => s === "from:no-reply" },
  { line: "A mail server marked it as possibly automatic.", match: (s) => s === "loop-header" || s === "x-autogenerated" },
];

/** Signals that say nothing about a message being automatic (no "why" line of their own). */
const NEUTRAL_SIGNALS: ReadonlySet<string> = new Set(["mailgun-spam", "process-failed", ATTENTION_SENT_SIGNAL]);

/** The stored `signals` JSON as a list of strings (anything else is ignored). */
function signalList(signals: unknown): string[] {
  return Array.isArray(signals) ? signals.filter((s): s is string => typeof s === "string") : [];
}

/**
 * The "why" lines under "The app isn't sure this is a real reply:" on a possible reply's card (M4-DESIGN §9.1.1): a
 * log-only recovery and a processing failure first (the failure as the `process-failed` signal or `autoReason`), then
 * one line per kind of signal in the table's order, each line once. When no signal has a line of its own: "Some signs
 * say it was sent automatically."
 */
export function possibleReplyReasons(signals: unknown, bodyAvailable: boolean, autoReason?: string | null): string[] {
  const list = signalList(signals);
  const out: string[] = [];
  if (bodyAvailable === false) out.push(WHY_LOG_ONLY);
  if (autoReason === "process-failed" || list.includes("process-failed")) out.push(WHY_PROCESS_FAILED);
  const specific = WHY_LINES.filter((w) => list.some(w.match)).map((w) => w.line);
  out.push(...specific);
  const unexplained = list.some((s) => !NEUTRAL_SIGNALS.has(s) && !WHY_LINES.some((w) => w.match(s)));
  if (specific.length === 0 && (unexplained || out.length === 0)) out.push(WHY_FALLBACK);
  return out;
}

// ───────────────────────── notifications (§5.1) ─────────────────────────

/** What the reply notifications need to know about one processed message (M4-DESIGN §5.1, §10 P1). */
export type ReplyCopyInput = {
  kind: InboundKindValue;
  autoReason?: string | null;
  /** The linked company, e.g. "Firma GmbH". */
  companyName?: string | null;
  /** The person the reply concerns (the linked email's recipient), e.g. "Anna Berg". */
  personName?: string | null;
  /** The sender's normalised address. */
  fromEmail: string;
  /** The known Person's name when `replierIsKnown` (else the From header's display name, never shown). */
  fromName?: string | null;
  /** The sender is a known Person (a live `Person.emailNorm` equals `fromEmail`). */
  replierIsKnown?: boolean;
  /** The sender is the person the linked email went to. */
  fromIsThreadPerson?: boolean;
  /** A known contact wrote a new email (linked to the company by their address, not to a thread). */
  newEmail?: boolean;
  /** Our email's subject in that thread (the first email's subject; a leading "Re: " is dropped). */
  threadSubject?: string | null;
  /** The received message's own subject. */
  subject?: string | null;
  /** `suggestedContact()` for a "has left the company" auto-reply. */
  suggested?: string | null;
  /** `replyScope().label`: "Dry run: " / "Test: " / "". */
  label?: ReplyLabel;
  /** Processing failed for good (the fail-safe, autoReason "process-failed"). */
  failed?: boolean;
  /** The company a domain hold (UNLINKED) or the fail-safe put on hold. */
  heldCompanyName?: string | null;
  /** A delivery-failure notice that only names other addresses: a forward from the person's mailbox failed. */
  forwardFailed?: boolean;
  /** A challenge without a strong automatic signal, filed as a possible reply (§3.4 rule 3). */
  possibleChallenge?: boolean;
  inboundId: number;
  companyId?: number | null;
  campaignId?: number | null;
  recipientId?: number | null;
  /** The address the linked email went to (the bounce notification names it). */
  toEmail?: string | null;
};

/** One notification to create (NotificationInput without the user). */
export type ReplyNotificationCopy = { type: string; title: string; body: string; link: string };

const SUBJECT_SHOWN_MAX = 150;

/** A subject for a sentence: whitespace collapsed, at most 150 characters, "(no subject)" when empty. */
function quoteSubject(s: string | null | undefined): string {
  const t = (s ?? "").replace(/\s+/g, " ").trim();
  if (!t) return "(no subject)";
  return t.length > SUBJECT_SHOWN_MAX ? `${t.slice(0, SUBJECT_SHOWN_MAX - 1).trimEnd()}…` : t;
}

/** Our thread subject without the "Re: " follow-ups carry. */
function threadSubjectText(s: string | null | undefined): string {
  return quoteSubject((s ?? "").replace(/^\s*(?:re\s*:\s*)+/i, ""));
}

const clean = (s: string | null | undefined) => (s ?? "").replace(/\s+/g, " ").trim();

/** A person's name for a sentence: "" for none and for a shared inbox ("General inbox" isn't anyone's name). */
function personalName(s: string | null | undefined): string {
  const name = clean(s);
  return name === GENERAL_INBOX_NAME ? "" : name;
}

/** How the sender is named: the thread person's name, a known colleague's name, or the address. */
function senderName(
  i: Pick<ReplyCopyInput, "fromIsThreadPerson" | "personName" | "fromName" | "replierIsKnown" | "fromEmail">,
): string {
  if (i.fromIsThreadPerson) return personalName(i.personName) || personalName(i.fromName) || i.fromEmail;
  if (i.replierIsKnown) return personalName(i.fromName) || i.fromEmail;
  return i.fromEmail;
}

/** How the person the email went to is named: their name, else their address. */
function threadPersonName(i: { personName?: string | null; toEmail?: string | null }): string {
  return personalName(i.personName) || clean(i.toEmail);
}

/** The first name of the person the email went to ("Anna"), else how they are named. */
function threadPersonFirstName(i: { personName?: string | null; toEmail?: string | null; fromEmail: string }): string {
  return firstNameFrom(personalName(i.personName)) || threadPersonName(i) || i.fromEmail;
}

/** "Anna Berg's" / "jonas@firma.de's". */
const possessive = (name: string) => (/s$/i.test(name) && !name.includes("@") ? `${name}'` : `${name}'s`);

/** `/notifications?reply=<id>#replies`: the page pins that reply (§4.3). */
export function replyLink(inboundId: number): string {
  return `/notifications?reply=${inboundId}#replies`;
}

/** The campaign's recipient panel, else the campaign, else the company. */
function recipientLink(i: ReplyCopyInput): string {
  if (i.campaignId && i.recipientId) return `/campaigns/${i.campaignId}?recipient=${i.recipientId}`;
  if (i.campaignId) return `/campaigns/${i.campaignId}`;
  if (i.companyId) return `/contacts?company=${i.companyId}`;
  return "/notifications";
}

function companyLink(i: ReplyCopyInput): string {
  return i.companyId ? `/contacts?company=${i.companyId}` : "/notifications";
}

function receivedCopy(i: ReplyCopyInput, prefix: string): ReplyNotificationCopy {
  const who = clean(i.companyName) || i.fromEmail;
  const name = senderName(i);
  const to = threadPersonName(i);
  let body: string;
  if (i.newEmail || !clean(i.threadSubject)) body = `${name} wrote to you: “${quoteSubject(i.subject)}”.`;
  else if (i.fromIsThreadPerson) body = `${name} replied to “${threadSubjectText(i.threadSubject)}”.`;
  else if (to) body = `${name} replied to your email to ${to} (“${threadSubjectText(i.threadSubject)}”).`;
  else body = `${name} replied to your email (“${threadSubjectText(i.threadSubject)}”).`;
  return { type: REPLY_NOTIFICATION.received, title: `${prefix}New reply from ${who}`, body, link: replyLink(i.inboundId) };
}

function possibleCopy(i: ReplyCopyInput, prefix: string): ReplyNotificationCopy {
  const who = clean(i.companyName) || i.fromEmail;
  return {
    type: REPLY_NOTIFICATION.possible,
    title: `${prefix}Did ${who} really reply?`,
    body:
      `The app can't tell whether ${possessive(senderName(i))} message is a real reply or an automatic one. ` +
      "Their follow-ups wait until you choose.",
    link: replyLink(i.inboundId),
  };
}

function unlinkedCopy(i: ReplyCopyInput, failed: boolean): ReplyNotificationCopy {
  const held = clean(i.heldCompanyName) || (failed ? clean(i.companyName) : "");
  const waits = held ? ` Follow-ups to ${held} wait until you do.` : "";
  const body = failed
    ? `The app couldn't read a message from ${i.fromEmail}, so it's listed here. Open it in your inbox, then decide on the Notifications page.${waits}`
    : `From ${i.fromEmail}: “${quoteSubject(i.subject)}”. Link it to a company so the right follow-ups stop.${waits}`;
  return { type: REPLY_NOTIFICATION.unlinked, title: "A reply we couldn't link to a company", body, link: replyLink(i.inboundId) };
}

function challengeCopy(i: ReplyCopyInput, prefix: string, possible: boolean): ReplyNotificationCopy {
  const person = threadPersonName(i) || clean(i.companyName) || i.fromEmail;
  const company = clean(i.companyName);
  const last = possible
    ? `Follow-ups to ${company || "this company"} wait until you choose Real reply or It was an auto-reply.`
    : "Follow-ups continue.";
  return {
    type: REPLY_NOTIFICATION.attention,
    title: `${prefix}${possessive(person)} spam filter is holding your email`,
    body: `It asks you to confirm you're a person. Open the message in your own inbox if you want to; the app never clicks such links. ${last}`,
    link: possible ? replyLink(i.inboundId) : companyLink(i),
  };
}

function leftCompanyCopy(i: ReplyCopyInput, prefix: string): ReplyNotificationCopy {
  const person = threadPersonName(i) || personalName(i.fromName) || i.fromEmail;
  const first = threadPersonFirstName(i);
  const company = clean(i.companyName);
  const suggested = clean(i.suggested);
  const suggestion = suggested ? `Their automatic reply suggests ${suggested} instead. ` : "";
  return {
    type: REPLY_NOTIFICATION.attention,
    title: `${prefix}${person} has left ${company || "the company"}`,
    body: `${suggestion}Follow-ups to ${first} continue unless you skip them in the campaign.`,
    link: recipientLink(i),
  };
}

function forwardFailedCopy(i: ReplyCopyInput, prefix: string): ReplyNotificationCopy {
  const person = threadPersonName(i) || i.fromEmail;
  const first = threadPersonFirstName(i);
  return {
    type: REPLY_NOTIFICATION.attention,
    title: `${prefix}A forward from ${possessive(person)} mailbox failed`,
    body:
      `${possessive(first)} mailbox passed your email on to another address, and that address doesn't work. ` +
      `${possessive(first)} own address is fine, so their follow-ups continue.`,
    link: recipientLink(i),
  };
}

function bounceCopy(i: ReplyCopyInput, prefix: string): ReplyNotificationCopy {
  const address = clean(i.toEmail) || personalName(i.personName) || "this address";
  return {
    type: REPLY_NOTIFICATION.bounce,
    title: `${prefix}An email to ${address} couldn't be delivered`,
    body: "A mail server sent back a delivery failure notice, so the follow-ups to this address stopped.",
    link: recipientLink(i),
  };
}

/**
 * The notification one processed message gives (M4-DESIGN §5.1), or null when its kind notifies nobody (§3.5):
 * - REPLY → `reply.received`; POSSIBLE_REPLY → `reply.possible` (a challenge filed as possible: `reply.attention`);
 * - UNLINKED → `reply.unlinked` (none when marked as spam);
 * - a processing failure (`failed`, autoReason "process-failed") → `reply.unlinked` with the failure text;
 * - AUTO_REPLY linked with "challenge" or "left-company" → `reply.attention`; other automatic replies → none;
 * - BOUNCE_NOTICE linked: a failed forward → `reply.attention`, else `reply.bounce`; delays → none;
 * - unlinked AUTO_REPLY / BOUNCE_NOTICE (no company), TEST_REPLY → none.
 * Titles start with the scope label ("Dry run: ", "Test: "). Throttling, quiet rows and who gets it are the caller's.
 */
export function replyNotificationCopy(i: ReplyCopyInput): ReplyNotificationCopy | null {
  const prefix = i.label ?? "";
  const failed = i.failed ?? i.autoReason === "process-failed";
  if (failed && (i.kind === "POSSIBLE_REPLY" || i.kind === "UNLINKED")) return unlinkedCopy(i, true);
  const linked = i.companyId !== null && i.companyId !== undefined;
  switch (i.kind) {
    case "REPLY":
      return receivedCopy(i, prefix);
    case "POSSIBLE_REPLY": {
      const challenge = i.possibleChallenge ?? i.autoReason === "challenge";
      return challenge ? challengeCopy(i, prefix, true) : possibleCopy(i, prefix);
    }
    case "UNLINKED":
      return i.autoReason === "spam" ? null : unlinkedCopy(i, false);
    case "AUTO_REPLY":
      if (!linked) return null;
      if (i.autoReason === "challenge") return challengeCopy(i, prefix, false);
      if (i.autoReason === "left-company") return leftCompanyCopy(i, prefix);
      return null;
    case "BOUNCE_NOTICE":
      if (!linked || i.autoReason === "delay") return null;
      return i.forwardFailed ? forwardFailedCopy(i, prefix) : bounceCopy(i, prefix);
    default:
      return null;
  }
}

/**
 * The grouped notice for replies processed more than 3 days after they arrived (M4-DESIGN §5.1 `reply.summary`): only
 * for the kinds on "Replies waiting for an answer" (a reply, a possible reply, an unlinked reply).
 */
export function replySummaryCopy(): ReplyNotificationCopy {
  return {
    type: REPLY_NOTIFICATION.summary,
    title: "Older replies were found",
    body: "They arrived more than 3 days ago, while the app couldn't process them. They're on Replies waiting for an answer.",
    link: "/notifications#replies",
  };
}

/** Where the grouped notice for older automatic messages points: the app's own entries under Emails & replies. */
export const AUTO_SUMMARY_LINK = "/activity?person=system&kind=emails";

/**
 * The grouped notice for older messages that are never on the waiting list but would have told the sender something
 * (a delivery failure notice, a spam filter check, a "left the company" or failed-forward notice), processed more than
 * 3 days after they arrived. Same type as `replySummaryCopy`, its own text and link, so it never points at a list the
 * messages aren't on.
 */
export function replyAutoSummaryCopy(): ReplyNotificationCopy {
  return {
    type: REPLY_NOTIFICATION.summary,
    title: "Older automatic messages were found",
    body:
      "Delivery failure notices or automatic replies arrived more than 3 days ago, while the app couldn't process them. " +
      "Follow-ups to an address that bounced have stopped; the others continue. See them under Activity › Emails & replies.",
    link: AUTO_SUMMARY_LINK,
  };
}

// ───────────────────────── activity summaries (§3.11) ─────────────────────────

/** The activity types whose summaries are built here (§3.11), plus the automatic status change. */
export type ReplyActivityType =
  | "reply.received"
  | "reply.auto"
  | "reply.possible"
  | "reply.bounce"
  | "reply.unlinked"
  | "reply.confirmed"
  | "reply.linked"
  | "reply.answered"
  | "reply.notNeeded"
  | "reply.reopened"
  | "company.status";

/** What an activity summary needs (the notification input's fields, plus who acted). */
export type ReplyActivityInput = Omit<ReplyCopyInput, "kind" | "inboundId"> & {
  type: ReplyActivityType;
  /** Who made a decision (confirmed, linked, answered, …), or linked the reply by hand. */
  actorName?: string | null;
  /** reply.received: the reply was linked by hand by this person. */
  linkedByName?: string | null;
  /** reply.confirmed: marked as a real reply (true) or as automatic (false). */
  real?: boolean;
  /** reply.bounce: a delay notice (the other server is still trying). */
  delay?: boolean;
};

/**
 * The one-line activity summary of a reply event (M4-DESIGN §3.11), without dates: "Anna Berg replied: “Re: 3D models
 * for your shop”", "Automatic reply from anna@firma.de (out of office)", "Ali marked the message from anna@firma.de as
 * a real reply", "Status changed to Replied: anna@firma.de replied".
 */
export function replyActivitySummary(i: ReplyActivityInput): string {
  const subject = `“${quoteSubject(i.subject)}”`;
  const actor = clean(i.actorName) || "Someone";
  const from = i.fromEmail;
  switch (i.type) {
    case "reply.received": {
      const name = senderName(i);
      const linkedBy = clean(i.linkedByName);
      if (linkedBy) return `${name} replied (linked by ${linkedBy}): ${subject}`;
      if (i.newEmail) return `${name} wrote: ${subject}`;
      const to = threadPersonName(i);
      if (i.fromIsThreadPerson || !to) return `${name} replied: ${subject}`;
      return `${name} replied to the email to ${to}: ${subject}`;
    }
    case "reply.auto":
      return `Automatic reply from ${from} (${autoReasonLabel(i.autoReason)})`;
    case "reply.possible":
      return `Message from ${from} may be a reply: follow-ups wait until someone checks it`;
    case "reply.bounce": {
      const address = clean(i.toEmail) || from;
      if (i.delay || i.autoReason === "delay") return `Delivery delay notice for ${address} (the other server is still trying)`;
      if (i.forwardFailed) return `Delivery failure notice after ${possessive(address)} mailbox forwarded the email: follow-ups continue`;
      return `Delivery failure notice for ${address}: follow-ups to this address stopped`;
    }
    case "reply.unlinked": {
      const held = clean(i.heldCompanyName);
      return `Reply from ${from} that couldn't be linked to a company${held ? ` (follow-ups to ${held} wait)` : ""}`;
    }
    case "reply.confirmed":
      return i.real
        ? `${actor} marked the message from ${from} as a real reply`
        : `${actor} marked the message from ${from} as an automatic reply: follow-ups continue`;
    case "reply.linked":
      return `${actor} linked the reply from ${from} to ${clean(i.companyName) || "a company"}`;
    case "reply.answered":
      return `${actor} answered the reply from ${from}`;
    case "reply.notNeeded":
      return `${actor} marked the reply from ${from} as needing no answer`;
    case "reply.reopened":
      return `${actor} put the reply from ${from} back on the waiting list`;
    case "company.status":
      return `Status changed to Replied: ${from} replied`;
    default:
      return `Message from ${from}`;
  }
}
