// "Is the build up to date?" — a fingerprint of everything that goes into the build
// (file sizes and modified times, not contents, so it takes a moment even for thousands of files).
// Written into .next after a successful build; start.bat compares it before starting.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

/** Files and folders that feed `npm run build`. */
export const BUILD_INPUTS = [
  "package-lock.json",
  "next.config.ts",
  "tsconfig.json",
  "tsconfig.worker.json",
  "postcss.config.mjs",
  "components.json",
  "prisma/schema.prisma",
  "scripts/build-worker.mjs",
  "src",
  "worker",
  "public",
];

/** Generated by the build itself (prisma generate), so never part of the fingerprint. */
export const BUILD_EXCLUDES = ["src/generated"];

const SKIP_DIRS = new Set(["node_modules", ".next", ".git", "dist"]);

/** Lines like "src/app/page.tsx|1234|1790106105204", sorted, for everything under the inputs. */
export function collectBuildEntries(root, inputs = BUILD_INPUTS, excludes = BUILD_EXCLUDES) {
  const excluded = new Set(excludes.map((e) => e.replace(/\\/g, "/")));
  const out = [];
  const visit = (rel) => {
    if (excluded.has(rel)) return;
    const abs = path.join(root, rel);
    let st;
    try {
      st = fs.statSync(abs);
    } catch {
      return; // optional input that doesn't exist (yet)
    }
    if (st.isDirectory()) {
      let names = [];
      try {
        names = fs.readdirSync(abs);
      } catch {
        return;
      }
      for (const name of names) {
        if (SKIP_DIRS.has(name)) continue;
        visit(rel ? `${rel}/${name}` : name);
      }
      return;
    }
    if (st.isFile()) out.push(`${rel}|${st.size}|${Math.floor(st.mtimeMs)}`);
  };
  for (const input of inputs) visit(input.replace(/\\/g, "/"));
  return out.sort();
}

/**
 * The fingerprint. The public address is included because next.config.ts reads it at build
 * time (allowed origins), so changing it needs a new build.
 */
export function computeBuildHash(root, { publicUrl = "", inputs, excludes } = {}) {
  const h = crypto.createHash("sha256");
  for (const line of collectBuildEntries(root, inputs, excludes)) h.update(line + "\n");
  h.update(`APP_PUBLIC_URL=${publicUrl}\n`);
  return h.digest("hex");
}

export function readBuildMarker(markerFile) {
  try {
    const data = JSON.parse(fs.readFileSync(markerFile, "utf8"));
    return typeof data?.hash === "string" ? data : null;
  } catch {
    return null;
  }
}

export function writeBuildMarker(markerFile, hash, extra = {}) {
  fs.mkdirSync(path.dirname(markerFile), { recursive: true });
  fs.writeFileSync(markerFile, JSON.stringify({ hash, builtAt: new Date().toISOString(), ...extra }, null, 2) + "\n", "utf8");
}

/**
 * Decides whether a build is needed.
 * reason: "missing" (never built), "worker-missing" (the background sender bundle is missing),
 * "changed" (files or the public address changed since the last build), or null.
 */
export function buildDecision({ buildIdExists, workerBundleExists, workerBuildScriptExists, marker, currentHash }) {
  if (!buildIdExists) return { needed: true, reason: "missing" };
  if (workerBuildScriptExists && !workerBundleExists) return { needed: true, reason: "worker-missing" };
  if (!marker || marker.hash !== currentHash) return { needed: true, reason: "changed" };
  return { needed: false, reason: null };
}
