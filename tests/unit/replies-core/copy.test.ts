describe("labels", () => {
  it("INBOUND_KIND_LABELS uses the A6 words", () => {
    expect(INBOUND_KIND_LABELS).toEqual({
      REPLY: "Reply",
      AUTO_REPLY: "Automatic reply",
      BOUNCE_NOTICE: "Delivery failure notice",
      POSSIBLE_REPLY: "Real reply?",
      UNLINKED: "Reply we couldn't link to a company",
      TEST_REPLY: "Reply to a test email",
    });
  });

  it("autoReasonLabel names every reason", () => {
    expect(
      ["out-of-office", "auto-reply", "helpdesk-ack", "challenge", "left-company", "read-receipt", "dsn", "delay", "process-failed", "internal", "spam"].map(
        autoReasonLabel,
      ),
    ).toEqual([
      "out of office",
      "automatic reply",
      "help desk confirmation",
      "spam filter check",
      "has left the company",
      "read receipt",
      "delivery failure",
      "delivery delay",
      "couldn't be read",
      "sent by your team",
      "marked as spam by Mailgun",
    ]);
    expect(autoReasonLabel(null)).toBe("automatic reply");
    expect(autoReasonLabel("something-new")).toBe("automatic reply");
  });
});

describe("possibleReplyReasons (M4-DESIGN §9.1.1)", () => {
  const one = (signals: string[]) => possibleReplyReasons(signals, true);

  it("has a line per signal", () => {
    expect(one(["challenge"])).toEqual(["It looks like a spam filter asking you to confirm you're a person."]);
    expect(one(["ack"])).toEqual(["It looks like an automatic \"we received your message\" confirmation."]);
    expect(one(["body:ack"])).toEqual(one(["ack"]));
    expect(one(["helpdesk"])).toEqual(["It came through a help desk, which marks every email as automatic."]);
    expect(one(["helpdesk-mailer"])).toEqual(one(["helpdesk"]));
    expect(one(["body:absence-details"])).toEqual(["It says when they're back, like an out-of-office message."]);
    expect(one(["body:absence"])).toEqual(["It says they're away, but it may also contain a real answer."]);
    expect(one(["x-auto-response-suppress"])).toEqual([
      "It carries a \"don't auto-reply\" marker that some mail programs add to normal emails too.",
    ]);
    expect(one(["body:left-company"])).toEqual(["It mentions someone leaving the company."]);
    expect(one(["subject:absence-word"])).toEqual(["Its subject mentions a holiday or leave."]);
    for (const s of ["list-headers", "precedence:bulk", "precedence:list", "feedback-id"]) {
      expect(one([s])).toEqual(["It looks like a newsletter or mailing-list email."]);
    }
    expect(one(["from:no-reply"])).toEqual(["It came from a no-reply address."]);
    expect(one(["loop-header"])).toEqual(["A mail server marked it as possibly automatic."]);
    expect(one(["x-autogenerated"])).toEqual(one(["loop-header"]));
    expect(one(["something-else"])).toEqual(["Some signs say it was sent automatically."]);
  });

  it("puts the log-only and failure lines first, then each line once in table order", () => {
    expect(possibleReplyReasons([], false)).toEqual(["It was recovered from Mailgun's log without its text, because the PC was off too long."]);
    expect(possibleReplyReasons([], true, "process-failed")).toEqual([
      "The app couldn't read this message, so it held the company's follow-ups to be safe. Open it in your inbox.",
    ]);
    expect(possibleReplyReasons(["process-failed"], true)).toEqual(possibleReplyReasons([], true, "process-failed"));
    expect(one(["list-headers", "feedback-id", "helpdesk", "helpdesk-mailer"])).toEqual([
      "It came through a help desk, which marks every email as automatic.",
      "It looks like a newsletter or mailing-list email.",
    ]);
  });

  it("adds the general line only when nothing more specific explains it", () => {
    expect(possibleReplyReasons(["subject:auto-prefix"], false)).toEqual([
      "It was recovered from Mailgun's log without its text, because the PC was off too long.",
      "Some signs say it was sent automatically.",
    ]);
    expect(one(["helpdesk", "auto-submitted:auto-generated", "x-auto-response-suppress"])).toHaveLength(2);
    expect(one([])).toEqual(["Some signs say it was sent automatically."]);
    expect(one(["mailgun-spam", "body:absence"])).toEqual(["It says they're away, but it may also contain a real answer."]);
  });

  it("ignores the processor's 'attention notice sent' marker", () => {
    expect(one(["challenge", ATTENTION_SENT_SIGNAL])).toEqual(one(["challenge"]));
    expect(one([ATTENTION_SENT_SIGNAL])).toEqual(one([]));
  });

  it("reads the classifier's signals of the possible-reply vectors", () => {
    expect(possibleReplyReasons(classify(vector("V11").in).signals, true)).toEqual([
      "It came through a help desk, which marks every email as automatic.",
      "It carries a \"don't auto-reply\" marker that some mail programs add to normal emails too.",
    ]);
    expect(possibleReplyReasons(classify(vector("V21").in).signals, true)).toContain(
      "It looks like a spam filter asking you to confirm you're a person.",
    );
  });

  it("ignores stored signals that aren't a list of strings", () => {
    expect(possibleReplyReasons({ junk: true }, true)).toEqual(["Some signs say it was sent automatically."]);
    expect(possibleReplyReasons(["challenge", 5, null], true)).toHaveLength(1);
  });
});

describe("replyNotificationCopy (M4-DESIGN §5.1)", () => {
  it("reply.received: the person we emailed", () => {
    expect(replyNotificationCopy(anna)).toEqual({
      type: "reply.received",
      title: "New reply from Firma GmbH",
      body: "Anna Berg replied to “3D models for your shop”.",
      link: "/notifications?reply=42#replies",
    });
  });

  it("reply.received: a known colleague, an unknown colleague, a known contact's new email, no company name", () => {
    const ben = { ...anna, fromEmail: "ben@firma.de", fromName: "Ben Braun", fromIsThreadPerson: false };
    expect(replyNotificationCopy(ben)?.body).toBe("Ben Braun replied to your email to Anna Berg (“3D models for your shop”).");
    const jonas = { ...anna, fromEmail: "jonas@firma.de", fromName: "Jonas", replierIsKnown: false, fromIsThreadPerson: false };
    expect(replyNotificationCopy(jonas)?.body).toBe("jonas@firma.de replied to your email to Anna Berg (“3D models for your shop”).");
    const newEmail = { ...ben, newEmail: true, subject: "Question about prices", threadSubject: null, personName: null };
    expect(replyNotificationCopy(newEmail)?.body).toBe("Ben Braun wrote to you: “Question about prices”.");
    expect(replyNotificationCopy({ ...anna, companyName: null })?.title).toBe("New reply from anna@firma.de");
    expect(replyNotificationCopy({ ...anna, threadSubject: "Re: 3D models for your shop" })?.body).toBe(
      "Anna Berg replied to “3D models for your shop”.",
    );
  });

  it("puts the scope label in front of the title", () => {
    expect(replyNotificationCopy({ ...anna, label: "Dry run: " })?.title).toBe("Dry run: New reply from Firma GmbH");
    expect(replyNotificationCopy({ ...anna, label: "Test: " })?.title).toBe("Test: New reply from Firma GmbH");
    expect(replyNotificationCopy({ ...anna, kind: "POSSIBLE_REPLY", label: "Dry run: " })?.title).toBe("Dry run: Did Firma GmbH really reply?");
  });

  it("reply.possible", () => {
    expect(replyNotificationCopy({ ...anna, kind: "POSSIBLE_REPLY", autoReason: "out-of-office" })).toEqual({
      type: "reply.possible",
      title: "Did Firma GmbH really reply?",
      body: "The app can't tell whether Anna Berg's message is a real reply or an automatic one. Their follow-ups wait until you choose.",
      link: "/notifications?reply=42#replies",
    });
  });

  it("reply.unlinked, with a domain hold", () => {
    const unlinked: ReplyCopyInput = {
      kind: "UNLINKED",
      fromEmail: "jonas@firma.de",
      subject: "Your 3D offer",
      inboundId: 5,
      companyId: null,
    };
    expect(replyNotificationCopy(unlinked)).toEqual({
      type: "reply.unlinked",
      title: "A reply we couldn't link to a company",
      body: "From jonas@firma.de: “Your 3D offer”. Link it to a company so the right follow-ups stop.",
      link: "/notifications?reply=5#replies",
    });
    expect(replyNotificationCopy({ ...unlinked, heldCompanyName: "Firma GmbH" })?.body).toBe(
      "From jonas@firma.de: “Your 3D offer”. Link it to a company so the right follow-ups stop. Follow-ups to Firma GmbH wait until you do.",
    );
    expect(replyNotificationCopy({ ...unlinked, subject: "" })?.body).toContain("“(no subject)”");
  });

  it("the processing-failure (fail-safe) variant", () => {
    const failed: ReplyCopyInput = { kind: "UNLINKED", autoReason: "process-failed", fromEmail: "jonas@firma.de", inboundId: 6 };
    expect(replyNotificationCopy(failed)).toEqual({
      type: "reply.unlinked",
      title: "A reply we couldn't link to a company",
      body: "The app couldn't read a message from jonas@firma.de, so it's listed here. Open it in your inbox, then decide on the Notifications page.",
      link: "/notifications?reply=6#replies",
    });
    const held = { ...anna, kind: "POSSIBLE_REPLY" as const, autoReason: "process-failed", failed: true };
    expect(replyNotificationCopy(held)?.type).toBe("reply.unlinked");
    expect(replyNotificationCopy(held)?.body).toBe(
      "The app couldn't read a message from anna@firma.de, so it's listed here. Open it in your inbox, then decide on the Notifications page. Follow-ups to Firma GmbH wait until you do.",
    );
  });

  it("reply.summary", () => {
    expect(replySummaryCopy()).toEqual({
      type: "reply.summary",
      title: "Older replies were found",
      body: "They arrived more than 3 days ago, while the app couldn't process them. They're on Replies waiting for an answer.",
      link: "/notifications#replies",
    });
  });

  it("the grouped notice for older automatic messages never points at the waiting list (NOTIFY-02, SPEC-05)", () => {
    const copy = replyAutoSummaryCopy();
    expect(copy).toEqual({
      type: "reply.summary",
      title: "Older automatic messages were found",
      body:
        "Delivery failure notices or automatic replies arrived more than 3 days ago, while the app couldn't process them. " +
        "Follow-ups to an address that bounced have stopped; the others continue. See them under Activity › Emails & replies.",
      link: AUTO_SUMMARY_LINK,
    });
    expect(copy.link).toBe("/activity?person=system&kind=emails");
    expect(copy.body).not.toContain("waiting for an answer");
    expect(copy.link).not.toBe(replySummaryCopy().link);
  });

  it("reply.attention for a challenge: automatic, and filed as a possible reply", () => {
    const auto = { ...anna, kind: "AUTO_REPLY" as const, autoReason: "challenge", fromEmail: "verify@mailguard.example", fromIsThreadPerson: false };
    expect(replyNotificationCopy(auto)).toEqual({
      type: "reply.attention",
      title: "Anna Berg's spam filter is holding your email",
      body: "It asks you to confirm you're a person. Open the message in your own inbox if you want to; the app never clicks such links. Follow-ups continue.",
      link: "/contacts?company=1042",
    });
    const possible = { ...auto, kind: "POSSIBLE_REPLY" as const, possibleChallenge: true };
    expect(replyNotificationCopy(possible)).toEqual({
      type: "reply.attention",
      title: "Anna Berg's spam filter is holding your email",
      body:
        "It asks you to confirm you're a person. Open the message in your own inbox if you want to; the app never clicks such links. " +
        "Follow-ups to Firma GmbH wait until you choose Real reply or It was an auto-reply.",
      link: "/notifications?reply=42#replies",
    });
    // The challenge hint alone picks the same copy; an explicit false gives the plain possible-reply copy.
    expect(replyNotificationCopy({ ...possible, possibleChallenge: undefined })?.type).toBe("reply.attention");
    expect(replyNotificationCopy({ ...possible, possibleChallenge: false })?.type).toBe("reply.possible");
    expect(replyNotificationCopy({ ...auto, label: "Test: " })?.title).toBe("Test: Anna Berg's spam filter is holding your email");
  });

  it("reply.attention when someone has left the company, with and without a suggested address", () => {
    const left = { ...anna, kind: "AUTO_REPLY" as const, autoReason: "left-company", suggested: "info@firma.de" };
    expect(replyNotificationCopy(left)).toEqual({
      type: "reply.attention",
      title: "Anna Berg has left Firma GmbH",
      body: "Their automatic reply suggests info@firma.de instead. Follow-ups to Anna continue unless you skip them in the campaign.",
      link: "/campaigns/7?recipient=99",
    });
    expect(replyNotificationCopy({ ...left, suggested: null })?.body).toBe("Follow-ups to Anna continue unless you skip them in the campaign.");
  });

  it("reply.attention when a forward from the person's mailbox failed", () => {
    const fwd = { ...anna, kind: "BOUNCE_NOTICE" as const, autoReason: "dsn", fromEmail: "mailer-daemon@x.de", forwardFailed: true };
    expect(replyNotificationCopy(fwd)).toEqual({
      type: "reply.attention",
      title: "A forward from Anna Berg's mailbox failed",
      body: "Anna's mailbox passed your email on to another address, and that address doesn't work. Anna's own address is fine, so their follow-ups continue.",
      link: "/campaigns/7?recipient=99",
    });
  });

  it("reply.bounce", () => {
    const bounce = { ...anna, kind: "BOUNCE_NOTICE" as const, autoReason: "dsn", fromEmail: "mailer-daemon@googlemail.com" };
    expect(replyNotificationCopy(bounce)).toEqual({
      type: "reply.bounce",
      title: "An email to anna@firma.de couldn't be delivered",
      body: "A mail server sent back a delivery failure notice, so the follow-ups to this address stopped.",
      link: "/campaigns/7?recipient=99",
    });
    expect(replyNotificationCopy({ ...bounce, label: "Dry run: " })?.title).toBe("Dry run: An email to anna@firma.de couldn't be delivered");
    expect(replyNotificationCopy({ ...bounce, recipientId: null })?.link).toBe("/campaigns/7");
  });

  it("names a shared inbox ('General inbox') by its address, never as a person", () => {
    const info = { ...anna, personName: "General inbox", fromName: "General inbox", fromEmail: "info@firma.de", toEmail: "info@firma.de" };
    expect(replyNotificationCopy(info)?.body).toBe("info@firma.de replied to “3D models for your shop”.");
    const left = { ...info, kind: "AUTO_REPLY" as const, autoReason: "left-company" };
    expect(replyNotificationCopy(left)?.title).toBe("info@firma.de has left Firma GmbH");
    expect(replyNotificationCopy(left)?.body).toBe("Follow-ups to info@firma.de continue unless you skip them in the campaign.");
    expect(replyActivitySummary({ ...info, type: "reply.received" })).toBe("info@firma.de replied: “Re: 3D models for your shop”");
  });

  it("returns null for messages that notify nobody", () => {
    expect(replyNotificationCopy({ ...anna, kind: "AUTO_REPLY", autoReason: "out-of-office" })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "AUTO_REPLY", autoReason: "read-receipt" })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "AUTO_REPLY", autoReason: "challenge", companyId: null })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "BOUNCE_NOTICE", autoReason: "delay" })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "BOUNCE_NOTICE", autoReason: "dsn", companyId: null })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "UNLINKED", autoReason: "spam", companyId: null })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "TEST_REPLY", autoReason: "internal" })).toBeNull();
    expect(replyNotificationCopy({ ...anna, kind: "TEST_REPLY" })).toBeNull();
  });
});

describe("replyActivitySummary (M4-DESIGN §3.11)", () => {
  const base = { ...anna, subject: "Re: 3D models for your shop" };

  it("reply.received in every variant", () => {
    expect(replyActivitySummary({ ...base, type: "reply.received" })).toBe("Anna Berg replied: “Re: 3D models for your shop”");
    expect(replyActivitySummary({ ...base, type: "reply.received", fromEmail: "ben@firma.de", fromName: "Ben Braun", fromIsThreadPerson: false })).toBe(
      "Ben Braun replied to the email to Anna Berg: “Re: 3D models for your shop”",
    );
    expect(
      replyActivitySummary({ ...base, type: "reply.received", fromEmail: "jonas@firma.de", replierIsKnown: false, fromIsThreadPerson: false }),
    ).toBe("jonas@firma.de replied to the email to Anna Berg: “Re: 3D models for your shop”");
    expect(
      replyActivitySummary({
        ...base,
        type: "reply.received",
        fromEmail: "ben@firma.de",
        fromName: "Ben Braun",
        fromIsThreadPerson: false,
        newEmail: true,
        subject: "Question about prices",
      }),
    ).toBe("Ben Braun wrote: “Question about prices”");
    expect(
      replyActivitySummary({
        ...base,
        type: "reply.received",
        fromEmail: "jonas@firma.de",
        replierIsKnown: false,
        fromIsThreadPerson: false,
        linkedByName: "Ali",
        subject: "Your 3D offer",
      }),
    ).toBe("jonas@firma.de replied (linked by Ali): “Your 3D offer”");
  });

  it("automatic, possible, bounce and unlinked messages", () => {
    expect(replyActivitySummary({ ...base, type: "reply.auto", autoReason: "out-of-office" })).toBe("Automatic reply from anna@firma.de (out of office)");
    expect(replyActivitySummary({ ...base, type: "reply.possible" })).toBe(
      "Message from anna@firma.de may be a reply: follow-ups wait until someone checks it",
    );
    const notice = { ...base, fromEmail: "mailer-daemon@googlemail.com", toEmail: "anna@firma.de" };
    expect(replyActivitySummary({ ...notice, type: "reply.bounce" })).toBe(
      "Delivery failure notice for anna@firma.de: follow-ups to this address stopped",
    );
    expect(replyActivitySummary({ ...notice, type: "reply.bounce", delay: true })).toBe(
      "Delivery delay notice for anna@firma.de (the other server is still trying)",
    );
    expect(replyActivitySummary({ ...notice, type: "reply.bounce", forwardFailed: true })).toBe(
      "Delivery failure notice after anna@firma.de's mailbox forwarded the email: follow-ups continue",
    );
    const jonas = { fromEmail: "jonas@firma.de", subject: "Your 3D offer" };
    expect(replyActivitySummary({ ...jonas, type: "reply.unlinked" })).toBe("Reply from jonas@firma.de that couldn't be linked to a company");
    expect(replyActivitySummary({ ...jonas, type: "reply.unlinked", heldCompanyName: "Firma GmbH" })).toBe(
      "Reply from jonas@firma.de that couldn't be linked to a company (follow-ups to Firma GmbH wait)",
    );
  });

  it("decisions name who made them", () => {
    const d = { fromEmail: "anna@firma.de", actorName: "Ali" };
    expect(replyActivitySummary({ ...d, type: "reply.confirmed", real: true })).toBe("Ali marked the message from anna@firma.de as a real reply");
    expect(replyActivitySummary({ ...d, type: "reply.confirmed", real: false })).toBe(
      "Ali marked the message from anna@firma.de as an automatic reply: follow-ups continue",
    );
    expect(replyActivitySummary({ ...d, fromEmail: "jonas@firma.de", type: "reply.linked", companyName: "Firma GmbH" })).toBe(
      "Ali linked the reply from jonas@firma.de to Firma GmbH",
    );
    expect(replyActivitySummary({ ...d, type: "reply.answered" })).toBe("Ali answered the reply from anna@firma.de");
    expect(replyActivitySummary({ ...d, type: "reply.notNeeded" })).toBe("Ali marked the reply from anna@firma.de as needing no answer");
    expect(replyActivitySummary({ ...d, type: "reply.reopened" })).toBe("Ali put the reply from anna@firma.de back on the waiting list");
    expect(replyActivitySummary({ fromEmail: "anna@firma.de", type: "company.status" })).toBe("Status changed to Replied: anna@firma.de replied");
  });

  it("never contains a date", () => {
    const s = replyActivitySummary({ ...base, type: "reply.received" });
    expect(s).not.toMatch(/\d{4}|Sep|Oct/);
  });
});
